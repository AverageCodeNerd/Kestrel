FIRST = 0x20
LAST = 0x7E


def rows_to_bytes(rows):
    """Pack a glyph's art, one byte per row, bit 0 the leftmost pixel."""
    out = []
    for row in rows:
        bits = 0
        for column, cell in enumerate(row):
            if cell == "#":
                bits |= 1 << column
        out.append(bits)
    return out


def ordered():
    missing = [c for c in range(FIRST, LAST + 1) if chr(c) not in GLYPHS]
    if missing:
        raise SystemExit("no art for: " + " ".join(chr(c) for c in missing))
    return [(chr(c), GLYPHS[chr(c)]) for c in range(FIRST, LAST + 1)]


def escape(ch):
    if ch == "'":
        return "\\" + "'"
    if ch == "\\":
        return "\\\\"
    return ch


HEADER = [
    "//! An 8x16 bitmap font covering printable ASCII (0x20..=0x7E).",
    "//!",
    "//! Generated by `tools/font.py` from the ASCII art in that file. Edit the art",
    "//! there and re-run it; this table is not meant to be edited by hand.",
    "//!",
    "//! Each glyph is 16 bytes, one per row, top row first. Within a row the least",
    "//! significant bit is the leftmost pixel. Capitals occupy rows 2-11 and",
    "//! lowercase shares that baseline with descenders reaching row 14, so text",
    "//! drawn a cell at a time lines up without the caller knowing any of it.",
    "",
    "pub const GLYPH_WIDTH: usize = 8;",
    "pub const GLYPH_HEIGHT: usize = 16;",
    "",
]


def emit_rust(path):
    lines = list(HEADER)
    lines.append("pub const FIRST_CHAR: u8 = 0x%02X;" % FIRST)
    lines.append("pub const LAST_CHAR: u8 = 0x%02X;" % LAST)
    lines.append("")
    lines.append("/// Returns the glyph for `c`, falling back to `?` for anything unprintable.")
    lines.append("pub fn glyph(c: u8) -> &'static [u8; GLYPH_HEIGHT] {")
    lines.append("    let idx = if (FIRST_CHAR..=LAST_CHAR).contains(&c) {")
    lines.append("        (c - FIRST_CHAR) as usize")
    lines.append("    } else {")
    lines.append("        (b'?' - FIRST_CHAR) as usize")
    lines.append("    };")
    lines.append("    &FONT[idx]")
    lines.append("}")
    lines.append("")
    lines.append("#[rustfmt::skip]")
    lines.append("pub static FONT: [[u8; GLYPH_HEIGHT]; (LAST_CHAR - FIRST_CHAR + 1) as usize] = [")
    for ch, rows in ordered():
        packed = ", ".join("0x%02X" % b for b in rows_to_bytes(rows))
        lines.append("    [%s], // '%s'" % (packed, escape(ch)))
    lines.append("];")
    lines.append("")

    with open(path, "w", newline="\n") as handle:
        handle.write("\n".join(lines))
    return len(GLYPHS)


def paint(pixels, art, ox, oy, scale, colour):
    for y, row in enumerate(art):
        for x, cell in enumerate(row):
            if cell != "#":
                continue
            for sy in range(scale):
                for sx in range(scale):
                    pixels[ox + x * scale + sx, oy + y * scale + sy] = colour


def emit_preview(path):
    from PIL import Image

    columns = 16
    scale = 3
    pad = 2
    rows = (LAST - FIRST + columns) // columns
    cell_w = (WIDTH + pad) * scale
    cell_h = (HEIGHT + pad) * scale
    image = Image.new("RGB", (columns * cell_w, rows * cell_h), (10, 12, 18))
    pixels = image.load()
    for index, (_ch, art) in enumerate(ordered()):
        ox = (index % columns) * cell_w + scale
        oy = (index // columns) * cell_h + scale
        paint(pixels, art, ox, oy, scale, (208, 214, 224))
    image.save(path)


def emit_sample(path, lines):
    from PIL import Image

    scale = 2
    longest = max(len(line) for line in lines)
    image = Image.new(
        "RGB",
        (longest * WIDTH * scale + 16, len(lines) * HEIGHT * scale + 16),
        (10, 12, 18),
    )
    pixels = image.load()
    for row, line in enumerate(lines):
        for index, ch in enumerate(line):
            art = GLYPHS.get(ch, GLYPHS["?"])
            paint(
                pixels,
                art,
                8 + index * WIDTH * scale,
                8 + row * HEIGHT * scale,
                scale,
                (208, 214, 224),
            )
    image.save(path)


