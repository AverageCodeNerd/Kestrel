#!/usr/bin/env python3
"""Design source for Kestrel's console font.

Each glyph is drawn here as ASCII art on an 8x16 grid and emitted as the byte
table in `kernel/src/font.rs`. Editing the art and re-running this script is the
only supported way to change the font: the Rust file is generated, never edited
by hand.

    python tools/font.py            # rewrite kernel/src/font.rs
    python tools/font.py --preview  # also write build/font-preview.png

Grid conventions, which every glyph follows so the text lines up:

    row 0        blank (leading)
    rows 1-11    ascender zone; capitals occupy rows 2-11
    rows 5-11    x-height zone for lowercase
    row 11       last row above the baseline
    rows 12-14   descender zone
    row 15       blank (leading)
    columns 1-6  ink; column 0 and column 7 are the letter-spacing

Stems are two pixels wide. At scale 1 that is a light text face on a 1080p
screen; at scale 2 it is what the desktop uses by default.
"""

import sys
import os

WIDTH = 8
HEIGHT = 16

GLYPHS = {}


def g(ch, art):
    rows = [r for r in art.split("\n") if r.strip("\r") != ""]
    rows = [r.rstrip("\r") for r in rows]
    if len(rows) != HEIGHT:
        raise SystemExit("glyph %r has %d rows, want %d" % (ch, len(rows), HEIGHT))
    for r in rows:
        if len(r) != WIDTH:
            raise SystemExit("glyph %r has a row of %d columns: %r" % (ch, len(r), r))
        if set(r) - set(".#"):
            raise SystemExit("glyph %r has stray characters: %r" % (ch, r))
    GLYPHS[ch] = rows


